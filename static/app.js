function escapeSvg(text){
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function wrapStationLabel(name, maxLen = 12){
  const words = String(name).split(/\s+/);
  const lines = [];
  let current = '';
  for(const word of words){
    if(!current || (current + ' ' + word).trim().length <= maxLen){
      current = (current + ' ' + word).trim();
    }else{
      lines.push(current);
      current = word;
    }
  }
  if(current) lines.push(current);
  if(lines.length <= 2) return lines;
  return [lines[0], lines.slice(1).join(' ')];
}

function buildSnakePoints(corridor){
  const n = corridor.length;

  // V8.17: use a taller virtual canvas, closer to the card aspect ratio.
  // This prevents the SVG from looking horizontally compressed in the middle.
  const width = 780;
  const left = 78;
  const right = 702;
  const points = [];

  if(n <= 6){
    const height = 340;
    const y = 170;
    corridor.forEach((station, idx) => {
      const x = n === 1 ? (left + right) / 2 : left + ((right - left) * idx / (n - 1));
      points.push({ station, x, y, row: 0, pos: idx });
    });
    return { width, height, points };
  }

  if(n <= 12){
    const height = 560;
    const topCount = Math.ceil(n / 2);
    const bottomCount = n - topCount;
    const top = corridor.slice(0, topCount);
    const bottom = corridor.slice(topCount);
    const topY = 120;
    const bottomY = 430;

    top.forEach((station, idx) => {
      const ratio = topCount === 1 ? 0.5 : idx / (topCount - 1);
      const x = left + ((right - left) * ratio);
      points.push({ station, x, y: topY, row: 0, pos: idx });
    });

    bottom.forEach((station, idx) => {
      const ratio = bottomCount === 1 ? 0.5 : idx / (bottomCount - 1);
      const x = right - ((right - left) * ratio);
      points.push({ station, x, y: bottomY, row: 1, pos: idx });
    });

    return { width, height, points };
  }

  const height = 660;
  const rowYs = [90, 330, 570];
  const first = Math.ceil(n / 3);
  const second = Math.ceil((n - first) / 2);
  const third = n - first - second;
  const counts = [first, second, third];

  let cursor = 0;
  counts.forEach((count, rowIndex) => {
    const segment = corridor.slice(cursor, cursor + count);
    cursor += count;
    const reverse = rowIndex % 2 === 1;
    segment.forEach((station, idx) => {
      const ratio = count === 1 ? 0.5 : idx / (count - 1);
      const x = reverse ? right - ((right - left) * ratio) : left + ((right - left) * ratio);
      points.push({ station, x, y: rowYs[rowIndex], row: rowIndex, pos: idx });
    });
  });

  return { width, height, points };
}

