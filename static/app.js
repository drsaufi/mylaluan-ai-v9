function updateStationOptions(selected = null){
  const line = document.getElementById("line").value;
  const search = (document.getElementById("station_search")?.value || "").toLowerCase();
  const stations = stationMap[line] || [];
  const selectedSet = new Set(selected || defaultStationsForLine(line));
  const container = document.getElementById("station_chips");
  const selectedContainer = document.getElementById("selected_chips");
  const hint = document.getElementById("station_count_hint");

  if(hint){
    hint.textContent = `${stations.length} stations referenced on ${line}`;
  }

  const visible = stations.filter(s => s.station.toLowerCase().includes(search));
  container.innerHTML = visible.map(s => {
    const checked = selectedSet.has(s.station) ? "checked" : "";
    const tag = s.interchange ? `<span class="station-tag">Interchange</span>` : "";
    return `<label class="station-row ${checked ? "selected" : ""}">
      <input type="checkbox" value="${s.station}" ${checked} onchange="syncSelectedChips()" />
      <span class="station-name">${s.station}</span>${tag}
    </label>`;
  }).join("");

  const selectedList = Array.from(selectedSet).filter(s => stations.some(x => x.station === s));
  selectedContainer.innerHTML = selectedList.length ? selectedList.map(s => `<button type="button" class="selected-chip" onclick="toggleStation('${escapeAttr(s)}', false)">${s}<span>×</span></button>`).join("") : `<span class="empty-chip">No affected stations selected</span>`;
  renderNetworkCoverage(line, lastResult);
}

function escapeAttr(text){
  return String(text).replaceAll("'", "\\'").replaceAll('"', '&quot;');
}

function syncSelectedChips(){
  const selected = getSelectedStations();
  const search = document.getElementById("station_search");
  if(search) search.value = "";
  updateStationOptions(selected);
}

function toggleStation(station, desired){
  const selected = new Set(getSelectedStations());
  if(desired === false) selected.delete(station); else selected.add(station);
  updateStationOptions(Array.from(selected));
}

function clearStations(){
  updateStationOptions([]);
}

function defaultStationsForLine(line){
  if(line === "Kelana Jaya Line") return ["KL Sentral", "Pasar Seni", "Masjid Jamek"];
  if(line === "MRT Kajang Line") return ["Merdeka", "Tun Razak Exchange"];
  if(line === "Monorail Line") return ["Bukit Bintang"];
  return (stationMap[line] || []).slice(0,2).map(s=>s.station);
}

function getSelectedStations(){
  return Array.from(document.querySelectorAll('#station_chips input[type="checkbox"]:checked')).map(cb => cb.value);
}

