function goToStep(stepId){
  if(!stepsUnlocked.has(stepId)) return;
  currentStep = stepId;

  // Show/hide step panels
  document.querySelectorAll(".sl-step").forEach(panel => {
    const id = panel.id.replace("step-", "");
    panel.classList.toggle("active", id === stepId);
  });

  // Update rail buttons + connector lines
  const order = STEPS.indexOf(stepId);
  document.querySelectorAll(".sl-rail-btn").forEach(btn => {
    const bStep = btn.dataset.step;
    const bOrder = STEPS.indexOf(bStep);
    btn.classList.remove("active","done","locked");
    if(bStep === stepId) btn.classList.add("active");
    else if(bOrder < order) btn.classList.add("done");
    if(!stepsUnlocked.has(bStep)) btn.classList.add("locked");
  });
  STEPS.forEach((_, i) => {
    const line = document.getElementById(`rl-${i}`);
    if(!line) return;
    line.classList.remove("active","done");
    if(i < order - 1) line.classList.add("done");
    else if(i === order - 1) line.classList.add("active");
  });

  // Update stage control panel
  const content = STAGE_CONTENT[stepId] || STAGE_CONTENT.command;
  const kicker = document.getElementById("sl-stage-kicker");
  const desc   = document.getElementById("sl-stage-desc");
  const btns   = document.getElementById("sl-stage-btns");
  if(kicker) kicker.textContent = content.kicker;
  if(desc)   desc.textContent   = content.desc;
  if(btns)   btns.innerHTML     = content.btns
    .map(b => `<button class="btn ${b.cls}" onclick="${b.fn}">${b.label}</button>`)
    .join("");

  window.scrollTo({top:0, behavior:"smooth"});
}

