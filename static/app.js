// â”€â”€ LLM health check â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
async function checkLLMHealth(){
  const badge = document.getElementById("llm_health_badge");
  const mode = document.getElementById("llm_health_mode");
  const model = document.getElementById("llm_health_model");
  const provider = document.getElementById("llm_health_provider");
  const message = document.getElementById("llm_health_message");

  if(badge){
    badge.className = "llm-badge fallback";
    badge.textContent = "Checking...";
  }
  if(message) message.textContent = "Testing API key and model connection...";

  try{
    const response = await fetch("/llm-health");
    const data = await response.json();
    const ready = !!data.llm_ready;

    if(badge){
      badge.className = `llm-badge ${ready ? "active" : "fallback"}`;
      badge.textContent = ready ? "LLM active" : "Fallback mode";
    }
    if(mode) mode.textContent = data.mode || (ready ? "LLM active" : "Template fallback");
    if(model) model.textContent = data.model || "gpt-5.4-mini";
    if(provider) provider.textContent = data.provider || "None";
    if(message) message.textContent = data.message || data.status || "LLM health check completed.";
  }catch(error){
    if(badge){
      badge.className = "llm-badge fallback";
      badge.textContent = "Fallback mode";
    }
    if(mode) mode.textContent = "Template fallback";
    if(provider) provider.textContent = "None";
    if(message) message.textContent = `Health check failed: ${error}. App can still run using fallback templates.`;
  }
}
